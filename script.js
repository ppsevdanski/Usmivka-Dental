function translate(key, values = {}) {
  const template = translations[currentLanguage][key] || translations.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}

function applyLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = language === 'en' ? 'Usmivka Dental Studio | Troyan' : 'Дентално студио Усмивка | Троян';
  document.querySelector('meta[name="description"]').content = language === 'en'
    ? 'Usmivka Dental Studio in Troyan. Preventive, cosmetic and family dentistry with personal care.'
    : 'Дентално студио Усмивка в Троян. Профилактика, естетична стоматология и индивидуална грижа за цялото семейство.';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.innerHTML = translate(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    element.dataset.i18nAttr.split(';').forEach((entry) => {
      const [attribute, key] = entry.split(':');
      element.setAttribute(attribute, translate(key));
    });
  });
  document.querySelector('#language-code').textContent = language === 'en' ? 'BG' : 'EN';
  if (bookingState.date) {
    document.querySelector('#selected-date-label').textContent = formatDate(bookingState.date);
  }
  if (bookingState.service && document.querySelector('.booking-step[data-step="3"]').classList.contains('active')) {
    renderBookingSummary();
  }
  renderCalendar();
}

function renderBookingSummary() {
  document.querySelector('#booking-summary').innerHTML = `<span><strong>${translate('summaryDate')}:</strong> ${formatDate(bookingState.date)}</span><span><strong>${translate('summaryService')}:</strong> ${translate(serviceKeys[bookingState.service])}</span><span><strong>${translate('summaryTime')}:</strong> ${bookingState.time}</span>`;
}

function setStepCaption(step) {
  const stepKey = ['stepOne', 'stepTwo', 'stepThree'][step - 1];
  document.querySelector('.step-caption').textContent = translate(stepKey);
  document.querySelector('.booking-progress').setAttribute('aria-label', translate('stepProgress', { step }));
}

function localDateString(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function isWorkday(dateString) {
  if (!dateString) return false;
  const [year, month, day] = dateString.split('-').map(Number);
  const dayOfWeek = new Date(year, month - 1, day).getDay();
  return dayOfWeek !== 0 && dayOfWeek !== 6;
}

function formatDate(dateString) {
  const [year, month, day] = dateString.split('-').map(Number);
  const locale = currentLanguage === 'en' ? 'en-GB' : 'bg-BG';
  return new Intl.DateTimeFormat(locale, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' })
    .format(new Date(year, month - 1, day));
}

function renderCalendar() {
  const year = calendarMonth.getFullYear();
  const month = calendarMonth.getMonth();
  const firstWeekday = new Date(year, month, 1).getDay();
  const dayOffset = (firstWeekday + 6) % 7;
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  const todayString = localDateString(today);
  const locale = currentLanguage === 'en' ? 'en-GB' : 'bg-BG';
  const monthLabel = new Intl.DateTimeFormat(locale, { month: 'long', year: 'numeric' }).format(calendarMonth);
  document.querySelector('#calendar-month').textContent = monthLabel;
  document.querySelector('#calendar-prev').disabled = year === today.getFullYear() && month === today.getMonth();

  const daysContainer = document.querySelector('#calendar-days');
  daysContainer.replaceChildren();
  for (let blank = 0; blank < dayOffset; blank += 1) {
    const spacer = document.createElement('span');
    spacer.className = 'calendar-spacer';
    spacer.setAttribute('aria-hidden', 'true');
    daysContainer.append(spacer);
  }

  for (let day = 1; day <= daysInMonth; day += 1) {
    const date = new Date(year, month, day);
    const dateString = localDateString(date);
    const dayButton = document.createElement('button');
    dayButton.type = 'button';
    dayButton.className = 'calendar-day';
    dayButton.textContent = String(day);
    dayButton.dataset.date = dateString;
    dayButton.setAttribute('aria-label', formatDate(dateString));
    dayButton.setAttribute('aria-pressed', String(dateString === bookingState.date));
    dayButton.disabled = dateString < todayString || !isWorkday(dateString);
    if (dateString === todayString) dayButton.classList.add('today');
    if (dateString === bookingState.date) dayButton.classList.add('selected');
    dayButton.addEventListener('click', () => {
      bookingState.date = dateString;
      dateInput.value = dateString;
      clearError('date-error');
      renderCalendar();
    });
    daysContainer.append(dayButton);
  }
}

function showStep(step) {
  document.querySelectorAll('.booking-step').forEach((panel) => {
    const active = Number(panel.dataset.step) === step;
    panel.hidden = !active;
    panel.classList.toggle('active', active);
  });
  document.querySelectorAll('.progress-dot').forEach((dot, index) => {
    dot.classList.toggle('active', index < step);
  });
  setStepCaption(step);
  document.querySelector('.booking-success').hidden = true;
}

function clearError(id) {
  document.querySelector(`#${id}`).textContent = '';
}

function openBooking() {
  bookingModal.classList.add('open');
  bookingModal.setAttribute('aria-hidden', 'false');
  document.body.classList.add('modal-open');
  bookingForm.reset();
  bookingState.date = '';
  bookingState.service = '';
  bookingState.time = '';
  calendarMonth = new Date(today.getFullYear(), today.getMonth(), 1);
  renderCalendar();
  slotsContainer.innerHTML = `<p class="slots-placeholder">${translate('selectServiceFirst')}</p>`;
  ['date-error', 'slot-error', 'phone-error'].forEach(clearError);
  showStep(1);
  window.setTimeout(() => document.querySelector('.calendar-day:not(:disabled)')?.focus(), 50);
}

function closeBooking() {
  bookingModal.classList.remove('open');
  bookingModal.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('modal-open');
}

function renderTimeSlots() {
  bookingState.time = '';
  if (!bookingState.service || !isWorkday(bookingState.date)) {
    slotsContainer.innerHTML = `<p class="slots-placeholder">${translate('selectServiceFirst')}</p>`;
    return;
  }

  const dateOffset = Number(bookingState.date.slice(-2)) % 4;
  const serviceOffset = [...bookingState.service].reduce((sum, character) => sum + character.charCodeAt(0), 0) % 3;
  const unavailable = new Set([(dateOffset + serviceOffset) % availableTimes.length]);
  slotsContainer.innerHTML = availableTimes
    .filter((_, index) => !unavailable.has(index))
    .map((time) => `<button type="button" data-time="${time}" aria-pressed="false">${time}</button>`)
    .join('');

  slotsContainer.querySelectorAll('button').forEach((button) => {
    button.addEventListener('click', () => {
      slotsContainer.querySelectorAll('button').forEach((slot) => {
        slot.classList.remove('selected');
        slot.setAttribute('aria-pressed', 'false');
      });
      button.classList.add('selected');
      button.setAttribute('aria-pressed', 'true');
      bookingState.time = button.dataset.time;
      clearError('slot-error');
    });
  });
}

function goToServiceStep() {
  const selectedDate = dateInput.value;
  const today = localDateString(new Date());
  if (!selectedDate || selectedDate < today) {
    document.querySelector('#date-error').textContent = translate('dateRequired');
    return;
  }
  if (!isWorkday(selectedDate)) {
    document.querySelector('#date-error').textContent = translate('dateWeekend');
    return;
  }

  bookingState.date = selectedDate;
  document.querySelector('#selected-date-label').textContent = formatDate(selectedDate);
  clearError('date-error');
  showStep(2);
  serviceInput.focus();
}

function goToPhoneStep() {
  if (!serviceInput.value) {
    document.querySelector('#slot-error').textContent = translate('serviceRequired');
    serviceInput.focus();
    return;
  }
  if (!bookingState.time) {
    document.querySelector('#slot-error').textContent = translate('timeRequired');
    return;
  }

  bookingState.service = serviceInput.value;
  renderBookingSummary();
  clearError('slot-error');
  showStep(3);
  document.querySelector('#booking-phone').focus();
}

